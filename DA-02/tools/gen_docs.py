"""Generates the documentation that is derived from the model: data dictionary, DAX reference, ERD (Mermaid) and the report spec."""
import os, json
import model_spec as ms
import gen_powerbi as gp
import gen_report as gr
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HDR = "<!-- GENERATED by tools/build_repo.py - do not edit by hand -->\n"
def w(path, text):
    full = os.path.join(ROOT, path); os.makedirs(os.path.dirname(full), exist_ok=True); open(full, "w", newline="\n").write(text)

def dictionary():
    o = [HDR, "# Data dictionary\n\nEvery column of the warehouse (`dw.*`) and how it appears in Power BI. Hidden columns are keys and raw numeric columns; users work with **measures** (see [DAX reference](dax-reference.md)).\n"]
    for t in ms.ALL + [ms.SEC]:
        o.append(f"\n## {t.model}  (`{'dw.' + t.name if t.kind != 'sec' else 'sec.user_territory_map'}`)\n\n{t.desc}  \n**Grain:** {t.grain}  \n**Type:** {'dimension' if t.kind == 'dim' else 'fact' if t.kind == 'fact' else 'security'}\n\n")
        o.append("| Column (SQL) | Power BI name | SQL type | Hidden | Key / FK | Description |\n|---|---|---|:-:|---|---|\n")
        for c in t.cols:
            key = ("PK " if c.pk else "") + (f"→ {c.fk}" if c.fk else "")
            o.append(f"| `{c.name}` | {c.display} | `{c.ty}` | {'yes' if c.hidden else ''} | {key.strip()} | {c.desc} |\n")
    w("docs/data-dictionary.md", "".join(o))

def dax_reference():
    meas = gp.parse_measures(); o = [HDR, "# DAX reference\n\nAll measures live in the `_Measures` table. Conventions: fiscal year = July-June (named by the year it ends); time intelligence uses the single conformed `Date` table (marked as date table, contiguous); `DIVIDE` everywhere to avoid divide-by-zero; no implicit measures (`discourageImplicitMeasures`).\n\n"
         "**Patterns worth knowing**\n\n- *Rolling windows* use `Date[Month Index]` instead of `DATESINPERIOD`, which includes an extra day when the window starts on a 31st.\n- *Headcount* is semi-additive: it returns the snapshot of the **last month-end in the selected period** (`LASTNONBLANK`).\n- *YoY* uses `SAMEPERIODLASTYEAR`; use fiscal-year or month granularity - partial calendar years are not like-for-like (data ends 29 Jun 2025).\n- *Role-playing dates*: `Order Date` is the active relationship; `Ship Date`/`Due Date` are inactive and used via `USERELATIONSHIP` (`Net Sales by Ship Date`).\n"]
    folders = []
    for m in meas:
        if m["folder"] not in folders: folders.append(m["folder"])
    for f in folders:
        o.append(f"\n## {f}\n")
        for m in [x for x in meas if x["folder"] == f]:
            o.append(f"\n### {m['name']}\n\n{m['desc']}" + (f"  \nFormat: `{m['fmt']}`" if m["fmt"] else "") + f"\n\n```dax\n{m['name']} =\n{m['expr']}\n```\n")
    w("docs/dax-reference.md", "".join(o))
    return len(meas)

def erd():
    rels = ms.relationships(); L = ["```mermaid", "erDiagram"]
    for f, c, d, dc, active in rels:
        role = ms.ROLE.get(c.name, "")
        label = (role or c.name.replace("_key", "")) + ("" if active else " (inactive)")
        L.append(f'    {f.model.replace(" ", "_")} }}o--|| {d.model.replace(" ", "_")} : "{label}"')
    L.append("```")
    return "\n".join(L), rels

def data_model():
    mer, rels = erd(); act = sum(1 for r in rels if r[4])
    o = [HDR, f"# Data model\n\nA **constellation (galaxy) star schema**: 6 fact tables share 11 conformed dimensions. {len(rels)} relationships in the Power BI model ({act} active, {len(rels) - act} inactive role-playing date relationships). All relationships are single-direction, many-to-one, dimension → fact; there are no bi-directional filters, which keeps row-level security predictable.\n\n",
         "![Star schema](assets/erd.svg)\n\n", mer, "\n\n## Tables and grain\n\n| Table | Power BI name | Grain | Notes |\n|---|---|---|---|\n"]
    for t in ms.ALL: o.append(f"| `dw.{t.name}` | {t.model} | {t.grain} | {t.desc} |\n")
    o.append("\n## Design decisions\n\n"
      "- **Surrogate keys** (identity) on every dimension except `dim_date` (yyyymmdd). Each dimension has an **unknown member** (`-1`) so a failed lookup never drops fact rows; a WARN data-quality check reports how often it is used.\n"
      "- **SCD type 1** everywhere. AdventureWorks carries history only where it matters here: product cost (used at *fact load* via `ProductCostHistory` by order date, so COGS is historically correct) and employee department (captured in the month-end headcount snapshot).\n"
      "- **Region = sales territory.** Facts that have no native region get one at load time: purchases → vendor main-office territory, employees/payroll → home-address territory. Every fact therefore joins `Territory` directly, so one RLS filter secures all of them.\n"
      "- **Freight and tax** are header-level amounts; they are allocated to lines by revenue share so line-grain facts still reconcile to `SalesOrderHeader` (tested to ±$1).\n"
      "- **Privacy by design:** no national ID, birth date, gender, login or pay rate is loaded. Payroll is aggregated to department × territory × month so individual pay cannot be derived from the model.\n"
      "- **Inventory** has no history in AdventureWorks and no region; it is a company-wide current snapshot (see [assumptions](assumptions-and-limitations.md)).\n"
      "- **Import mode** (not DirectQuery): fastest visuals, and RLS is evaluated in the model.\n")
    w("docs/data-model.md", "".join(o))

def report_spec():
    pages = gr.build_pages()
    o = [HDR, "# Report specification\n\nThe PBIR report in `powerbi/EnterpriseBI.Report` is generated from `tools/gen_report.py`. This page lists what each page contains so you can (a) review it, (b) rebuild it by hand if the generated project does not open, and (c) use it as a storyboard for the demo.\n\n"
         "Canvas 1280 × 720 (16:9), light theme. Import `powerbi/theme/EnterpriseBI-theme.json` via *View → Themes → Browse for themes*. Slicers for Fiscal Year and Territory are synchronised across pages.\n"]
    for p in pages:
        o.append(f"\n## {p.title}" + (f"  *(drill-through on {p.drill[0]}[{p.drill[1]}])*" if p.drill else "") + "\n\n| Visual | Title | Fields |\n|---|---|---|\n")
        for _, v in p.visuals:
            vv = v["visual"]; title = ""
            if "visualContainerObjects" in vv: title = vv["visualContainerObjects"]["title"][0]["properties"]["text"]["expr"]["Literal"]["Value"].strip("'")
            fields = []
            for role, st in vv.get("query", {}).get("queryState", {}).items():
                fields.append(f"**{role}:** " + ", ".join(pr["queryRef"] for pr in st["projections"]))
            o.append(f"| {vv['visualType']} | {title} | {'; '.join(fields)} |\n")
    o.append("\n## If the generated project does not open\n\n1. Open Power BI Desktop → new report → *Get data → SQL Server* and load the 17 `rpt.vw_*` views plus `rpt.vw_sec_user_territory` (or run the M files in `powerbi/power-query/`).\n"
             "2. Create the relationships listed in [data-model.md](data-model.md); mark `Date` as the date table; set *Sort by column* as in the [data dictionary](data-dictionary.md).\n"
             "3. In *DAX query view* paste `powerbi/dax/measures_dax_query_view.dax` and choose *Update model: add new measures*.\n"
             "4. Build pages from the tables above. For each drill-through page: *Format → Page information → Allow drill-through*, drop the field named in the heading into *Drill through → Add drill-through fields here*.\n"
             "5. Create roles from `powerbi/dax/rls.dax` (Modeling → Manage roles).\n")
    w("docs/report-spec.md", "".join(o))

def run():
    dictionary(); n = dax_reference(); data_model(); report_spec(); return n
