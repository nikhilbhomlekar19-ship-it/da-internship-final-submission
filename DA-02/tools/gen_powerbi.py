"""Generates Power Query (M) files, the TMDL semantic model (PBIP) and the DAX query-view script from tools/model_spec.py
and powerbi/dax/measures.dax."""
import os, re, uuid, json
import model_spec as ms

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PBI = "powerbi"
MODEL_DIR = f"{PBI}/EnterpriseBI.SemanticModel"
REPORT_DIR = f"{PBI}/EnterpriseBI.Report"
NS = uuid.UUID("6f1c2a52-8d7e-4c1b-9a53-2b0e5f4d7a10")
guid = lambda s: str(uuid.uuid5(NS, s))

def w(path, text, mode="w"):
    full = os.path.join(ROOT, path); os.makedirs(os.path.dirname(full), exist_ok=True)
    open(full, mode, newline="\n").write(text)

def tq(n):  # TMDL name quoting
    return n if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", n) else "'" + n.replace("'", "''") + "'"

# ------------------------------------------------------------------ measures
def parse_measures():
    txt = open(os.path.join(ROOT, PBI, "dax", "measures.dax"), encoding="utf-8").read()
    blocks = re.split(r"(?m)^//@ ", txt)[1:]
    out = []
    for b in blocks:
        head, _, body = b.partition("\n")
        meta = dict(p.strip().split(":", 1) for p in head.split("|"))
        meta = {k.strip(): v.strip() for k, v in meta.items()}
        body = body.rstrip()
        name, _, expr = body.partition(" =")
        out.append(dict(name=name.strip(), expr=expr.strip("\n").strip() if "\n" not in expr.strip() else expr.lstrip(" ").lstrip("\n").rstrip(),
                        folder=meta.get("folder", ""), fmt=meta.get("format", ""), desc=meta.get("desc", "")))
    return out

# ------------------------------------------------------------------ types / M
def tmdl_type(ty):
    if ty in ("int", "smallint", "tinyint", "bigint"): return "int64"
    if ty == "bit": return "boolean"
    if ty == "date" or ty == "datetime": return "dateTime"
    if ty.startswith("decimal(19") or ty == "money": return "decimal"
    if ty.startswith("decimal"): return "double"
    return "string"

def m_type(ty):
    return {"int64": "Int64.Type", "boolean": "type logical", "dateTime": "type date", "decimal": "Currency.Type", "double": "type number", "string": "type text"}[tmdl_type(ty)]

def m_query(t):
    cols = t.cols
    ren = ", ".join(f'{{"{c.name}", "{c.display}"}}' for c in cols)
    steps = [f'    Source = Sql.Database(p_SqlServer, p_Database)', f'    Data = Source{{[Schema = "rpt", Item = "vw_{t.name}"]}}[Data]',
             f'    Renamed = Table.RenameColumns(Data, {{{ren}}})']
    last = "Renamed"
    txt = [c.display for c in cols if tmdl_type(c.ty) == "string"]
    if t.kind == "dim" and txt:
        trim = ", ".join(f'{{"{n}", Text.Trim, type text}}' for n in txt)
        steps.append(f'    Trimmed = Table.TransformColumns({last}, {{{trim}}})'); last = "Trimmed"
        names = ", ".join(f'"{n}"' for n in txt)
        steps.append(f'    NoNulls = Table.ReplaceValue({last}, null, "N/A", Replacer.ReplaceValue, {{{names}}})'); last = "NoNulls"
    typed = ", ".join(f'{{"{c.display}", {m_type(c.ty)}}}' for c in cols)
    steps.append(f'    Typed = Table.TransformColumnTypes({last}, {{{typed}}})')
    return "let\n" + ",\n".join(steps) + "\nin\n    Typed"

def gen_m():
    hdr = "// GENERATED by tools/build_repo.py - paste into Power BI Desktop > Transform data > New Source > Blank Query > Advanced Editor if you build the model by hand.\n"
    w(f"{PBI}/power-query/00_parameters.pq",
      hdr + '// Create two parameters (Home > Manage parameters). Text, required:\n//   p_SqlServer = "localhost"     (or yourserver.database.windows.net)\n//   p_Database  = "AW_BI"\n'
      '"localhost" meta [IsParameterQuery=true, Type="Text", IsParameterQueryRequired=true]\n"AW_BI" meta [IsParameterQuery=true, Type="Text", IsParameterQueryRequired=true]\n')
    for t in ms.ALL + [ms.SEC]:
        q = m_query(t) if t.name != "sec_user_territory" else m_query_sec()
        w(f"{PBI}/power-query/{t.model}.pq", hdr + f"// Table: {t.model}  <- rpt.vw_{t.name}\n" + q + "\n")
    w(f"{PBI}/power-query/_Measures.pq", hdr + "// Empty table that hosts the measures\nlet\n    Source = #table(type table [Placeholder = Int64.Type], {{1}})\nin\n    Source\n")

def m_query_sec():
    t = ms.SEC
    ren = ", ".join(f'{{"{c.name}", "{c.display}"}}' for c in t.cols)
    return ('let\n    Source = Sql.Database(p_SqlServer, p_Database),\n    Data = Source{[Schema = "rpt", Item = "vw_sec_user_territory"]}[Data],\n'
            f'    Renamed = Table.RenameColumns(Data, {{{ren}}}),\n    Typed = Table.TransformColumnTypes(Renamed, {{{{"User Email", type text}}, {{"Territory Key", Int64.Type}}}})\nin\n    Typed')

# ------------------------------------------------------------------ TMDL
def indent_expr(expr, tabs):
    pad = "\t" * tabs
    return "\n".join(pad + ln if ln.strip() else "" for ln in expr.split("\n"))

def col_block(t, c):
    s = f"\tcolumn {tq(c.display)}\n\t\tdataType: {tmdl_type(c.ty)}\n"
    if c.hidden: s += "\t\tisHidden\n"
    if t.name == "dim_date" and c.name == "full_date": s += "\t\tisKey\n"
    ty = tmdl_type(c.ty)
    fmt = c.fmt or ("0" if ty == "int64" else "dd mmm yyyy" if ty == "dateTime" else "\\$#,0.00" if ty == "decimal" else "#,0.00" if ty == "double" else None)
    if fmt: s += f"\t\tformatString: {fmt}\n"
    s += f"\t\tlineageTag: {guid(t.name + '.' + c.name)}\n\t\tsummarizeBy: none\n\t\tsourceColumn: {c.display}\n"
    if c.sort_by: s += f"\t\tsortByColumn: {tq(t.col(c.sort_by).display)}\n"
    return s + "\n"

HIER = {"dim_date": [("Fiscal Calendar", ["fiscal_year_label", "fiscal_quarter_label", "year_month_label"]), ("Calendar", ["calendar_year", "quarter_name", "month_name"])],
        "dim_product": [("Product Hierarchy", ["product_category", "product_subcategory", "product_name"])],
        "dim_territory": [("Geography", ["territory_group", "country_region_name", "territory_name"])]}

def table_tmdl(t, partition_m, hidden=False):
    s = f"/// {t.desc}\ntable {tq(t.model)}\n\tlineageTag: {guid('table.' + t.name)}\n"
    if t.name == "dim_date": s += "\tdataCategory: Time\n"
    if hidden: s += "\tisHidden\n"
    s += "\n" + "".join(col_block(t, c) for c in t.cols)
    for hn, lv in HIER.get(t.name, []):
        s += f"\thierarchy {tq(hn)}\n\t\tlineageTag: {guid(t.name + '.h.' + hn)}\n"
        for l in lv:
            s += f"\t\tlevel {tq(t.col(l).display)}\n\t\t\tlineageTag: {guid(t.name + '.h.' + hn + '.' + l)}\n\t\t\tcolumn: {tq(t.col(l).display)}\n"
        s += "\n"
    s += f"\tpartition {tq(t.model)} = m\n\t\tmode: import\n\t\tsource =\n{indent_expr(partition_m, 3)}\n"
    return s

def measures_tmdl(measures):
    s = "/// Hosts all report measures (no data).\ntable _Measures\n\tlineageTag: %s\n\n" % guid("table._Measures")
    s += "\tcolumn Placeholder\n\t\tdataType: int64\n\t\tisHidden\n\t\tformatString: 0\n\t\tlineageTag: %s\n\t\tsummarizeBy: none\n\t\tsourceColumn: Placeholder\n\n" % guid("_Measures.Placeholder")
    for m in measures:
        s += f"\t/// {m['desc']}\n" if m["desc"] else ""
        multi = "\n" in m["expr"]
        if multi: s += f"\tmeasure {tq(m['name'])} =\n{indent_expr(m['expr'], 3)}\n"
        else: s += f"\tmeasure {tq(m['name'])} = {m['expr']}\n"
        if m["fmt"]: s += f"\t\tformatString: {m['fmt']}\n"
        s += f"\t\tdisplayFolder: {m['folder']}\n\t\tlineageTag: {guid('measure.' + m['name'])}\n\n"
    s += "\tpartition _Measures = m\n\t\tmode: import\n\t\tsource =\n" + indent_expr('let\n    Source = #table(type table [Placeholder = Int64.Type], {{1}})\nin\n    Source', 3) + "\n"
    return s

def rel_name(f, c, d):
    role = ms.ROLE.get(c.name, "")
    return f"{f.model}_{(role or d.model).replace(' ', '')}_{d.model}".replace(" ", "") if role else f"{f.model}_{d.model}".replace(" ", "")

RLS_TERRITORY = ("COUNTROWS (\n    FILTER (\n        'Region Access',\n        'Region Access'[User Email] = USERPRINCIPALNAME ()\n"
                 "            && 'Region Access'[Territory Key] = Territory[Territory Key]\n    )\n) > 0")
RLS_ACCESS = "'Region Access'[User Email] = USERPRINCIPALNAME ()"

def gen_tmdl():
    meas = parse_measures()
    base = MODEL_DIR + "/definition"
    w(f"{MODEL_DIR}/definition.pbism", json.dumps({"$schema": "https://developer.microsoft.com/json-schemas/fabric/item/semanticModel/definitionProperties/1.0.0/schema.json", "version": "4.2", "settings": {}}, indent=2) + "\n")
    w(f"{MODEL_DIR}/.platform", json.dumps({"$schema": "https://developer.microsoft.com/json-schemas/fabric/gitIntegration/platformProperties/2.0.0/schema.json",
        "metadata": {"type": "SemanticModel", "displayName": "Enterprise BI Suite"}, "config": {"version": "2.0", "logicalId": guid("semanticmodel")}}, indent=2) + "\n")
    w(f"{base}/database.tmdl", "database\n\tcompatibilityLevel: 1601\n")
    tables = ["_Measures"] + [t.model for t in ms.ALL] + [ms.SEC.model]
    m = "model Model\n\tculture: en-US\n\tdefaultPowerBIDataSourceVersion: powerBI_V3\n\tdiscourageImplicitMeasures\n\tsourceQueryCulture: en-US\n\n"
    m += "".join(f"ref table {tq(n)}\n" for n in tables) + "\nref role 'Region Manager'\nref role 'Global Executive'\n\nref expression p_SqlServer\nref expression p_Database\n"
    w(f"{base}/model.tmdl", m)
    w(f"{base}/expressions.tmdl",
      f'expression p_SqlServer = "localhost" meta [IsParameterQuery=true, Type="Text", IsParameterQueryRequired=true]\n\tlineageTag: {guid("expr.p_SqlServer")}\n\n'
      f'expression p_Database = "AW_BI" meta [IsParameterQuery=true, Type="Text", IsParameterQueryRequired=true]\n\tlineageTag: {guid("expr.p_Database")}\n')
    w(f"{base}/tables/_Measures.tmdl", measures_tmdl(meas))
    for t in ms.ALL: w(f"{base}/tables/{t.model}.tmdl", table_tmdl(t, m_query(t)))
    w(f"{base}/tables/{ms.SEC.model}.tmdl", table_tmdl(ms.SEC, m_query_sec(), hidden=True))
    rel = ""
    for f, c, d, dc, active in ms.relationships():
        rel += f"relationship {rel_name(f, c, d)}\n" + ("" if active else "\tisActive: false\n") + f"\tfromColumn: {tq(f.model)}.{tq(c.display)}\n\ttoColumn: {tq(d.model)}.{tq(dc.display)}\n\n"
    w(f"{base}/relationships.tmdl", rel)
    w(f"{base}/roles/Region Manager.tmdl",
      "/// Dynamic RLS: a user sees only the territories mapped to their UPN in sec.user_territory_map (via the hidden 'Region Access' table).\n"
      f"role 'Region Manager'\n\tmodelPermission: read\n\n\ttablePermission Territory =\n{indent_expr(RLS_TERRITORY, 3)}\n\n\ttablePermission 'Region Access' = {RLS_ACCESS}\n")
    w(f"{base}/roles/Global Executive.tmdl", "/// No row filters: executives see every territory. Assign only trusted users.\nrole 'Global Executive'\n\tmodelPermission: read\n")
    w(f"{PBI}/dax/rls.dax", "// Row-level security (also defined in the TMDL roles). Test with: Modeling > View as > Region Manager + 'Other user'.\n"
      "// ---- Role: Region Manager ----\n// Table: Territory\n" + RLS_TERRITORY + "\n\n// Table: Region Access\n" + RLS_ACCESS + "\n\n// ---- Role: Global Executive ---- (no table filters)\n")
    # DAX query view script
    q = "// Paste into Power BI Desktop > DAX query view, then click 'Update model: Add new measure' on each (or 'Update model with changes').\nDEFINE\n"
    for mm in meas:
        q += f"\t/// {mm['desc']}\n\tMEASURE _Measures[{mm['name']}] =\n" + indent_expr(mm["expr"], 2) + "\n"
    q += "\nEVALUATE ROW ( \"Net Sales\", [Net Sales] )\n"
    w(f"{PBI}/dax/measures_dax_query_view.dax", q)
    return meas

def gen_pbip():
    w(f"{PBI}/EnterpriseBI.pbip", json.dumps({"$schema": "https://developer.microsoft.com/json-schemas/fabric/pbip/pbipProperties/1.0.0/schema.json", "version": "1.0",
        "artifacts": [{"report": {"path": "EnterpriseBI.Report"}}], "settings": {"enableAutoRecovery": True}}, indent=2) + "\n")

def run():
    gen_m(); meas = gen_tmdl(); gen_pbip()
    return meas
