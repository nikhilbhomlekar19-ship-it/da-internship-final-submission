"""Generates the SQL files that are derived from tools/model_spec.py and sql/transforms/*.sql"""
import os, textwrap
import model_spec as ms

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HDR = "-- GENERATED by tools/build_repo.py from tools/model_spec.py and sql/transforms/*.sql - do not edit by hand.\n"

def w(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    open(full, "w", newline="\n").write(text)

def q(s): return s.replace("'", "''")

def literal(v):
    return str(v)  # unknown-member values are already SQL literals

# ------------------------------------------------------------------ 02 staging
def gen_staging():
    o = [HDR, "-- 02_staging.sql : staging tables (raw copies of the source columns we need), ETL config seed and the local extract proc\n"]
    for t, spec in ms.STG.items():
        cols = ms.stg_cols(t)
        keys = spec["inc"][1] if "inc" in spec else []
        lines = []
        for n, ty, _ in cols:
            lines.append(f"    {n} {ty} {'NOT NULL' if n in keys else 'NULL'}")
        if keys:
            lines.append(f"    CONSTRAINT pk_stg_{t} PRIMARY KEY ({', '.join(keys)})")
        o.append(f"DROP TABLE IF EXISTS stg.{t};\nCREATE TABLE stg.{t} (\n" + ",\n".join(lines) + "\n);\nGO\n")
    # config seed
    o.append("DELETE FROM etl.source_table_config;\nGO\nINSERT INTO etl.source_table_config (source_schema, source_table, target_schema, target_table, load_type, watermark_column, key_columns, select_list, load_order) VALUES")
    rows = []
    for i, (t, spec) in enumerate(ms.STG.items(), 1):
        sch, tab = spec["src"].split(".")
        sel = ", ".join(f"[{src}]" if src == n else f"[{src}] AS [{n}]" for n, _, src in ms.stg_cols(t))
        inc = spec.get("inc")
        rows.append(f"\n ('{sch}', '{tab}', 'stg', '{t}', '{'INCREMENTAL' if inc else 'FULL'}', {q_or_null(inc[0]) if inc else 'NULL'}, "
                    f"{q_or_null(','.join(inc[1])) if inc else 'NULL'}, N'{q(sel)}', {i})")
    o.append(",".join(rows) + ";\nGO\n")
    o.append("DELETE FROM etl.watermark;\nGO\nINSERT INTO etl.watermark (table_name, last_watermark) VALUES\n" +
             ",\n".join(f" ('{t}', '1900-01-01')" for t, s in ms.STG.items() if "inc" in s) + ";\nGO\n")
    # local extract proc
    body = []
    for t, spec in ms.STG.items():
        cols = ms.stg_cols(t)
        names = ", ".join(n for n, _, _ in cols)
        sel = ", ".join(f"[{src}]" if src == n else f"[{src}] AS [{n}]" for n, _, src in cols)
        body.append(f"    SET @t0 = SYSUTCDATETIME();\n    TRUNCATE TABLE stg.{t};\n    INSERT INTO stg.{t} ({names}) SELECT {sel} FROM src.{t};\n"
                    f"    EXEC etl.usp_log_step @run_id, N'extract {t}', @t0, @@ROWCOUNT;\n")
    o.append("-- Requires the synonyms created by sql/02b_source_synonyms.sql (same-instance source database)\n"
             "CREATE OR ALTER PROCEDURE etl.usp_extract_local @run_id bigint = NULL\nAS\nBEGIN\n    SET NOCOUNT ON; SET XACT_ABORT ON;\n    DECLARE @t0 datetime2(3);\n"
             + "\n".join(body) + "END;\nGO\n")
    w("sql/02_staging.sql", "".join(o))
    syn = [HDR, "-- 02b_source_synonyms.sql : LOCAL mode only. Run with sqlcmd -v SourceDb=AdventureWorks2022 (or the name you restored the DB as)\n",
           "IF SCHEMA_ID(N'src') IS NULL EXEC (N'CREATE SCHEMA src');\nGO\n"]
    for t, spec in ms.STG.items():
        syn.append(f"DROP SYNONYM IF EXISTS src.{t};\nCREATE SYNONYM src.{t} FOR [$(SourceDb)].{spec['src']};\n")
    syn.append("GO\n")
    w("sql/02b_source_synonyms.sql", "".join(syn))

def q_or_null(s): return f"'{q(s)}'"

# ------------------------------------------------------------------ 03 dw schema
def coldef(c, ident_start=None):
    s = f"    {c.name} {c.ty}"
    if c.identity: s += " IDENTITY(1,1)"
    s += " NOT NULL" if (c.nullable is False or c.pk) else " NULL"
    return s

def gen_dw():
    o = [HDR, "-- 03_dw_schema.sql : star schema. RE-RUNNING DROPS AND RECREATES THE WAREHOUSE TABLES (they are rebuilt by the ETL).\n"]
    drop_order = [t for t in ms.FACTS] + [ms.BY_NAME["dim_employee"], ms.BY_NAME["dim_vendor"]] + \
                 [t for t in ms.DIMS if t.name not in ("dim_employee", "dim_vendor")]
    for t in drop_order: o.append(f"DROP TABLE IF EXISTS dw.{t.name};\n")
    o.append("GO\n")
    create_order = [ms.BY_NAME["dim_territory"]] + [t for t in ms.DIMS if t.name != "dim_territory"] + ms.FACTS
    for t in create_order:
        lines = [coldef(c) for c in t.cols]
        if t.kind == "dim":
            if t.name != "dim_date":
                lines += ["    etl_loaded_at datetime2(0) NOT NULL CONSTRAINT df_%s_loaded DEFAULT (SYSUTCDATETIME())" % t.name, "    etl_updated_at datetime2(0) NULL"]
        else:
            lines += ["    etl_loaded_at datetime2(0) NOT NULL CONSTRAINT df_%s_loaded DEFAULT (SYSUTCDATETIME())" % t.name]
        pk = [c.name for c in t.cols if c.pk]
        lines.append(f"    CONSTRAINT pk_{t.name} PRIMARY KEY CLUSTERED ({', '.join(pk)})")
        o.append(f"-- {t.desc}\n-- grain: {t.grain}\nCREATE TABLE dw.{t.name} (\n" + ",\n".join(lines) + "\n);\n")
        if t.kind == "dim" and t.nk and t.name != "dim_date":
            o.append(f"CREATE UNIQUE NONCLUSTERED INDEX ux_{t.name}_nk ON dw.{t.name} ({', '.join(t.nk)});\n")
        o.append("GO\n")
    o.append("-- foreign keys\n")
    for t in ms.FACTS + [ms.BY_NAME["dim_employee"], ms.BY_NAME["dim_vendor"]]:
        for c in t.cols:
            if c.fk:
                d, k = c.fk.split(".")
                o.append(f"ALTER TABLE dw.{t.name} ADD CONSTRAINT fk_{t.name}_{c.name} FOREIGN KEY ({c.name}) REFERENCES dw.{d} ({k});\n")
    o.append("GO\n")
    w("sql/03_dw_schema.sql", "".join(o))

# ------------------------------------------------------------------ 06/07 ETL procs
def transform(name):
    return open(os.path.join(ROOT, "sql", "transforms", name + ".sql")).read().rstrip().rstrip(";")

def gen_dim_proc(t):
    cols = [c.name for c in t.cols[1:]]
    nk = t.nk
    upd = [c for c in cols if c not in nk]
    unk = t.unknown
    ind = lambda s, n=8: textwrap.indent(s, " " * n)
    p = f"CREATE OR ALTER PROCEDURE etl.usp_load_{t.name} @run_id bigint = NULL\nAS\nBEGIN\n    SET NOCOUNT ON; SET XACT_ABORT ON;\n    DECLARE @t0 datetime2(3) = SYSUTCDATETIME(), @rows bigint = 0;\n\n"
    p += f"    IF OBJECT_ID(N'tempdb..#src') IS NOT NULL DROP TABLE #src;\n    SELECT * INTO #src FROM (\n{ind(transform(t.name))}\n    ) AS q;\n\n"
    p += (f"    -- unknown member (-1) so facts never lose rows to a missing lookup\n    IF NOT EXISTS (SELECT 1 FROM dw.{t.name} WHERE {t.key} = -1)\n    BEGIN\n"
          f"        SET IDENTITY_INSERT dw.{t.name} ON;\n        INSERT INTO dw.{t.name} ({t.key}, {', '.join(unk)})\n        VALUES (-1, {', '.join(literal(v) for v in unk.values())});\n"
          f"        SET IDENTITY_INSERT dw.{t.name} OFF;\n    END;\n\n")
    if upd:
        p += (f"    -- SCD type 1: overwrite changed attributes (NULL-safe comparison via EXCEPT)\n    UPDATE d SET {', '.join(f'd.{c} = s.{c}' for c in upd)}, d.etl_updated_at = SYSUTCDATETIME()\n"
              f"    FROM dw.{t.name} AS d JOIN #src AS s ON {' AND '.join(f's.{k} = d.{k}' for k in nk)}\n"
              f"    WHERE EXISTS (SELECT {', '.join('s.'+c for c in upd)} EXCEPT SELECT {', '.join('d.'+c for c in upd)});\n    SET @rows = @@ROWCOUNT;\n\n")
    p += (f"    INSERT INTO dw.{t.name} ({', '.join(cols)})\n    SELECT {', '.join('s.'+c for c in cols)} FROM #src AS s\n"
          f"    WHERE NOT EXISTS (SELECT 1 FROM dw.{t.name} AS d WHERE {' AND '.join(f'd.{k} = s.{k}' for k in nk)});\n    SET @rows = @rows + @@ROWCOUNT;\n\n"
          f"    EXEC etl.usp_log_step @run_id, N'load {t.name}', @t0, @rows;\nEND;\nGO\n")
    return p

def gen_fact_proc(t):
    cols = [c.name for c in t.cols]
    ind = lambda s, n=8: textwrap.indent(s, " " * n)
    return (f"CREATE OR ALTER PROCEDURE etl.usp_load_{t.name} @run_id bigint = NULL\nAS\nBEGIN\n    SET NOCOUNT ON; SET XACT_ABORT ON;\n    DECLARE @t0 datetime2(3) = SYSUTCDATETIME(), @rows bigint = 0;\n\n"
            f"    BEGIN TRANSACTION;   -- full rebuild is atomic: Power BI never reads a half-loaded fact\n        TRUNCATE TABLE dw.{t.name};\n"
            f"        INSERT INTO dw.{t.name} ({', '.join(cols)})\n{ind(transform(t.name))};\n        SET @rows = @@ROWCOUNT;\n    COMMIT TRANSACTION;\n\n"
            f"    EXEC etl.usp_log_step @run_id, N'load {t.name}', @t0, @rows;\nEND;\nGO\n")

def gen_etl():
    w("sql/06_etl_dimensions.sql", HDR + "-- 06_etl_dimensions.sql : SCD1 dimension loaders (dim_date is in 05_etl_dim_date.sql)\n" +
      "".join(gen_dim_proc(t) for t in ms.DIMS if t.name != "dim_date"))
    w("sql/07_etl_facts.sql", HDR + "-- 07_etl_facts.sql : fact loaders (atomic truncate + insert, key lookups against the dimensions)\n" +
      "".join(gen_fact_proc(t) for t in ms.FACTS))

# ------------------------------------------------------------------ 09 data quality + 10 views
def dq_checks():
    """[(name, layer, severity, sql)] - every query returns ONE number: violations (0 = pass). Portable SQL (also run in DuckDB by the tests)."""
    c = []
    for t in ms.FACTS:
        keys = ", ".join(t.nk)
        c.append((f"{t.name}: grain is unique", "dw", "ERROR", f"SELECT COUNT(*) FROM (SELECT {keys} FROM dw.{t.name} GROUP BY {keys} HAVING COUNT(*) > 1) AS x"))
    for t in ms.FACTS + [ms.BY_NAME["dim_employee"], ms.BY_NAME["dim_vendor"]]:
        for col in t.cols:
            if col.fk:
                d, k = col.fk.split(".")
                c.append((f"{t.name}.{col.name}: no orphan keys to {d}", "dw", "ERROR",
                          f"SELECT COUNT(*) FROM dw.{t.name} AS f LEFT JOIN dw.{d} AS d ON f.{col.name} = d.{k} WHERE f.{col.name} IS NOT NULL AND d.{k} IS NULL"))
    rec = lambda a, b: f"SELECT CASE WHEN {a} = {b} THEN 0 ELSE 1 END"
    c += [
     ("reconcile: sales lines = staging SalesOrderDetail rows", "dw", "ERROR", rec("(SELECT COUNT(*) FROM dw.fact_sales_line)", "(SELECT COUNT(*) FROM stg.SalesOrderDetail)")),
     ("reconcile: net sales = staging SUM(LineTotal)", "dw", "ERROR",
        "SELECT CASE WHEN ABS((SELECT SUM(net_sales_amount) FROM dw.fact_sales_line) - (SELECT SUM(LineTotal) FROM stg.SalesOrderDetail)) <= 0.05 THEN 0 ELSE 1 END"),
     ("reconcile: allocated freight = staging SUM(header Freight) (+-1.00)", "dw", "ERROR",
        "SELECT CASE WHEN ABS((SELECT SUM(allocated_freight_amount) FROM dw.fact_sales_line) - (SELECT SUM(Freight) FROM stg.SalesOrderHeader)) <= 1.00 THEN 0 ELSE 1 END"),
     ("reconcile: purchase lines = staging PurchaseOrderDetail rows", "dw", "ERROR", rec("(SELECT COUNT(*) FROM dw.fact_purchase_line)", "(SELECT COUNT(*) FROM stg.PurchaseOrderDetail)")),
     ("reconcile: purchase spend = staging SUM(LineTotal)", "dw", "ERROR",
        "SELECT CASE WHEN ABS((SELECT SUM(line_total_amount) FROM dw.fact_purchase_line) - (SELECT SUM(LineTotal) FROM stg.PurchaseOrderDetail)) <= 0.05 THEN 0 ELSE 1 END"),
     ("reconcile: inventory rows = staging ProductInventory rows", "dw", "ERROR", rec("(SELECT COUNT(*) FROM dw.fact_inventory)", "(SELECT COUNT(*) FROM stg.ProductInventory)")),
     ("reconcile: latest month-end headcount = current employees", "dw", "ERROR",
        "SELECT CASE WHEN (SELECT SUM(headcount_flag) FROM dw.fact_headcount_monthly WHERE month_end_date_key = (SELECT MAX(month_end_date_key) FROM dw.fact_headcount_monthly)) = (SELECT COUNT(*) FROM stg.Employee WHERE CurrentFlag = 1) THEN 0 ELSE 1 END"),
     ("reconcile: payroll employee-months = headcount snapshot rows", "dw", "ERROR", rec("(SELECT SUM(employee_count) FROM dw.fact_payroll_monthly)", "(SELECT SUM(headcount_flag) FROM dw.fact_headcount_monthly)")),
     ("sales: quantities and net sales are positive", "dw", "ERROR", "SELECT COUNT(*) FROM dw.fact_sales_line WHERE order_quantity <= 0 OR net_sales_amount < 0"),
     ("purchases: quantities are non-negative", "dw", "ERROR", "SELECT COUNT(*) FROM dw.fact_purchase_line WHERE order_quantity <= 0 OR received_quantity < 0 OR rejected_quantity < 0"),
     ("sales: unknown customer/product/territory lookups (late-arriving dimension)", "dw", "WARN", "SELECT COUNT(*) FROM dw.fact_sales_line WHERE customer_key = -1 OR product_key = -1 OR territory_key = -1"),
     ("purchases: unknown vendor/product/territory lookups", "dw", "WARN", "SELECT COUNT(*) FROM dw.fact_purchase_line WHERE vendor_key = -1 OR product_key = -1 OR territory_key = -1"),
     ("headcount: employees without a department at month end", "dw", "WARN", "SELECT COUNT(*) FROM dw.fact_headcount_monthly WHERE department_key = -1"),
     ("sales: lines costed with the product's current standard cost (no cost-history row)", "dw", "WARN",
        "SELECT COUNT(*) FROM stg.SalesOrderDetail AS d JOIN stg.SalesOrderHeader AS h ON h.SalesOrderID = d.SalesOrderID LEFT JOIN stg.ProductCostHistory AS c ON c.ProductID = d.ProductID AND h.OrderDate >= c.StartDate AND (c.EndDate IS NULL OR h.OrderDate <= c.EndDate) WHERE c.ProductID IS NULL"),
     ("staging: header/detail integrity (detail lines without a header)", "staging", "ERROR", "SELECT COUNT(*) FROM stg.SalesOrderDetail AS d LEFT JOIN stg.SalesOrderHeader AS h ON h.SalesOrderID = d.SalesOrderID WHERE h.SalesOrderID IS NULL"),
     ("staging: purchase detail without a header", "staging", "ERROR", "SELECT COUNT(*) FROM stg.PurchaseOrderDetail AS d LEFT JOIN stg.PurchaseOrderHeader AS h ON h.PurchaseOrderID = d.PurchaseOrderID WHERE h.PurchaseOrderID IS NULL"),
    ]
    return c

def gen_dq():
    o = [HDR, "-- 09_dq_checks.sql : data-quality gate (ERROR checks fail the pipeline, WARN checks are reported)\nDELETE FROM etl.dq_result;\nDELETE FROM etl.dq_check;\nGO\n",
         "INSERT INTO etl.dq_check (check_name, layer, severity, check_sql) VALUES\n"]
    o.append(",\n".join(f" (N'{q(n)}', N'{l}', N'{s}', N'{q(sql)}')" for n, l, s, sql in dq_checks()) + ";\nGO\n")
    o.append("""CREATE OR ALTER PROCEDURE etl.usp_run_dq_checks @run_id bigint = NULL, @fail_on_error bit = 1
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @batch uniqueidentifier = NEWID(), @id int, @name nvarchar(200), @sev nvarchar(10), @sql nvarchar(max), @n bigint, @failed int = 0;
    DECLARE @r TABLE (v bigint);
    DECLARE c CURSOR LOCAL FAST_FORWARD FOR SELECT check_id, check_name, severity, check_sql FROM etl.dq_check WHERE is_active = 1 ORDER BY check_id;
    OPEN c;
    FETCH NEXT FROM c INTO @id, @name, @sev, @sql;
    WHILE @@FETCH_STATUS = 0
    BEGIN
        DELETE FROM @r;
        SET @n = -1;
        BEGIN TRY
            INSERT INTO @r EXEC sys.sp_executesql @sql;
            SELECT @n = v FROM @r;
        END TRY
        BEGIN CATCH
            SET @n = -1;   -- a check that cannot run counts as a failure
        END CATCH
        INSERT INTO etl.dq_result (batch_id, run_id, check_id, check_name, severity, violations, status)
        VALUES (@batch, @run_id, @id, @name, @sev, @n, CASE WHEN @n = 0 THEN N'PASS' ELSE N'FAIL' END);
        IF @n <> 0 AND @sev = N'ERROR' SET @failed = @failed + 1;
        FETCH NEXT FROM c INTO @id, @name, @sev, @sql;
    END;
    CLOSE c; DEALLOCATE c;
    SELECT check_name, severity, status, violations FROM etl.dq_result WHERE batch_id = @batch ORDER BY CASE WHEN status = N'FAIL' THEN 0 ELSE 1 END, result_id;
    IF @failed > 0 AND @fail_on_error = 1
        THROW 51000, N'Data-quality gate failed: see etl.dq_result for the latest batch.', 1;
END;
GO
""")
    w("sql/09_dq_checks.sql", "".join(o))

def gen_views():
    o = [HDR, "-- 10_rpt_views.sql : the ONLY objects Power BI reads (stable contract; hides audit columns and the star's physical details)\n"]
    for t in ms.ALL:
        if not t.view: continue
        cols = [c.name for c in t.cols]
        o.append(f"CREATE OR ALTER VIEW rpt.vw_{t.name} AS\nSELECT {', '.join(cols)}\nFROM dw.{t.name};\nGO\n")
    o.append("CREATE OR ALTER VIEW rpt.vw_sec_user_territory AS\nSELECT LOWER(m.user_email) AS user_email, t.territory_key AS territory_key\n"
             "FROM sec.user_territory_map AS m JOIN dw.dim_territory AS t ON t.territory_id = m.territory_id\nWHERE m.is_active = 1;\nGO\n")
    w("sql/10_rpt_views.sql", "".join(o))

def run():
    gen_staging(); gen_dw(); gen_etl(); gen_dq(); gen_views()
