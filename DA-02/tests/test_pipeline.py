def test_yoy_fy2025_and_fiscal_ytd_and_rolling(wh):
    con, _ = wh
    fy = dict(con.execute("SELECT d.fiscal_year, SUM(f.net_sales_amount) FROM dw.fact_sales_line f JOIN dw.dim_date d ON d.date_key=f.order_date_key GROUP BY 1").fetchall())
    close(fy[2025] / fy[2024] - 1, BASE["sales"]["yoy_fy2025"], 1e-9)
    close(q1(con, "SELECT SUM(f.net_sales_amount) FROM dw.fact_sales_line f JOIN dw.dim_date d ON d.date_key=f.order_date_key WHERE d.fiscal_year=2025 AND d.month_index <= 2024*12+11"), BASE["sales"]["net_sales_fiscal_ytd_202412"])
    r = q1(con, "SELECT SUM(f.net_sales_amount)/3 FROM dw.fact_sales_line f JOIN dw.dim_date d ON d.date_key=f.order_date_key WHERE d.month_index > 2025*12+5-3 AND d.month_index <= 2025*12+5")
    close(r, BASE["sales"]["rolling_3m_avg_202506"])

def test_quota_attainment_fy2024(wh):
    con, _ = wh
    quota = q1(con, "SELECT SUM(q.quota_amount) FROM dw.fact_sales_quota q JOIN dw.dim_date d ON d.date_key=q.quota_month_key WHERE d.fiscal_year=2024")
    close(quota, BASE["quota"]["quota_fy2024"], 0.01)
