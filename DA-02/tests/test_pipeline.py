# ---------- HR
def test_headcount_and_payroll(wh):
    con, _ = wh
    H = BASE["hr"]
    assert q1(con, "SELECT SUM(headcount_flag) FROM dw.fact_headcount_monthly WHERE month_end_date_key=20101231") == H["headcount_201012"]
    assert q1(con, "SELECT SUM(headcount_flag) FROM dw.fact_headcount_monthly WHERE month_end_date_key=20250630") == H["headcount_202506"]
    close(q1(con, "SELECT SUM(estimated_payroll_cost) FROM dw.fact_payroll_monthly WHERE month_end_date_key=20101231"), H["payroll_cost_201012"], 0.5)
    close(q1(con, "SELECT SUM(estimated_payroll_cost) FROM dw.fact_payroll_monthly WHERE month_end_date_key=20250630"), H["payroll_cost_202506"], 0.5)
    assert q1(con, "SELECT SUM(employee_count) FROM dw.fact_payroll_monthly") == q1(con, "SELECT SUM(headcount_flag) FROM dw.fact_headcount_monthly")
    assert len(H["headcount_by_territory"]) == 10 and sum(H["headcount_by_territory"].values()) == H["headcount_202506"]   # guard against a vacuous loop
    got = dict(con.execute("SELECT t.territory_name, SUM(h.headcount_flag) FROM dw.fact_headcount_monthly h JOIN dw.dim_territory t ON t.territory_key=h.territory_key WHERE h.month_end_date_key=20250630 GROUP BY 1").fetchall())
    for k, v in H["headcount_by_territory"].items(): assert int(got[k]) == v

# ---------- date dimension
def test_date_dimension_is_contiguous_and_fiscal_logic_is_right(wh):
    con, _ = wh
    n, lo, hi = con.execute("SELECT COUNT(*), MIN(full_date), MAX(full_date) FROM dw.dim_date").fetchall()[0]
    assert n == (hi - lo).days + 1
    assert q1(con, "SELECT fiscal_year FROM dw.dim_date WHERE date_key=20240630") == 2024
    assert q1(con, "SELECT fiscal_year FROM dw.dim_date WHERE date_key=20240701") == 2025
    assert q1(con, "SELECT fiscal_month_number FROM dw.dim_date WHERE date_key=20240701") == 1
    assert q1(con, "SELECT COUNT(*) FROM dw.dim_date WHERE is_month_end=1") == q1(con, "SELECT COUNT(DISTINCT year_month_number) FROM dw.dim_date")
    assert q1(con, "SELECT COUNT(*) FROM dw.fact_sales_line f LEFT JOIN dw.dim_date d ON d.date_key=f.order_date_key WHERE d.date_key IS NULL") == 0

# ---------- the data-quality gate that ships in sql/09_dq_checks.sql, executed on the DuckDB warehouse
import gen_sql
@pytest.mark.parametrize("chk", gen_sql.dq_checks(), ids=lambda c: c[0][:70])
def test_dq_check(wh, chk):
    con, _ = wh
    name, layer, sev, sql = chk
    n = q1(con, harness.tsql_to_duck(sql))
    if sev == "ERROR":
        assert n == 0, f"{name}: {n} violations"
    elif "current standard cost" in name:
        assert n == BASE["sales"]["lines_without_cost_history"]   # documented: 64 lines fall back to Product.StandardCost
    else:
        assert n == 0, f"{name}: {n}"
