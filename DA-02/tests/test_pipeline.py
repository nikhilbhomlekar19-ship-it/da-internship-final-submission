"""Cross-checks the shipped SQL transforms (executed in DuckDB on the real AdventureWorks data)
against the independent pandas baseline in tests/baselines/expected_kpis.json.
Run:  AW_CSV_DIR=<folder with AdventureWorks CSVs + instawdb.sql> pytest -v tests/"""
import os, sys, json, pytest, sqlglot
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import model_spec as ms, harness

AW_DIR = os.environ.get("AW_CSV_DIR", os.path.join(ROOT, "data", "aw_oltp_csv"))
BASE = json.load(open(os.path.join(ROOT, "tests", "baselines", "expected_kpis.json")))
pytestmark = pytest.mark.skipif(not os.path.exists(os.path.join(AW_DIR, "instawdb.sql")), reason="AdventureWorks CSVs not found (run scripts/download_adventureworks.sh)")

@pytest.fixture(scope="session")
def wh():
    con, stats = harness.build(AW_DIR)
    return con, stats

def q1(con, sql):
    return con.execute(sql).fetchall()[0][0]

def close(a, b, tol=0.05):  # absolute currency tolerance (cents)
    assert abs(float(a) - float(b)) <= tol, f"{a} != {b}"

# ---------- static: transform SELECT aliases must equal the spec column order
@pytest.mark.parametrize("t", ms.ALL, ids=lambda t: t.name)
def test_transform_alias_order_matches_spec(t):
    if t.name == "dim_date": pytest.skip("dim_date is generated by etl.usp_load_dim_date")
    sql = open(os.path.join(ROOT, "sql", "transforms", t.name + ".sql")).read()
    sel = sqlglot.parse_one(sql, read="tsql")
    aliases = [e.alias_or_name for e in sel.expressions]
    expected = [c.name for c in (t.cols if t.kind == "fact" else t.cols[1:])]
    assert aliases == expected

